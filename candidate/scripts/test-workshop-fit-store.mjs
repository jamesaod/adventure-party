import assert from 'node:assert/strict';
import {savedFit,saveFit,resetFit,migrateFits} from '../js/mob-workshop-fit-store.mjs';
const fit={position:[1,2,3],rotation:[4,5,6],sizePercent:100};
const d={model:{id:'orc'},equipment:{main:'axe',off:'none',shield:'none',grips:{main:fit}}};
migrateFits(d);
assert.deepEqual(savedFit(d,'main'),fit);
d.equipment.main='sword';
assert.equal(savedFit(d,'main'),null,'stale slot fit must not migrate onto a different weapon');
saveFit(d,'main',{...fit,sizePercent:70});
d.equipment.main='axe';
assert.equal(savedFit(d,'main').sizePercent,100);
const copy=savedFit(d,'main');copy.position[0]=99;
assert.equal(savedFit(d,'main').position[0],1,'callers cannot mutate stored fits');
assert.equal(savedFit(d,'off','axe'),null,'left/right sockets are independent');
d.model.id='human';assert.equal(savedFit(d,'main'),null);
d.model.id='orc';
const restored=JSON.parse(JSON.stringify(d));
assert.equal(savedFit(restored,'main','sword').sizePercent,70);
resetFit(restored,'main');assert.equal(savedFit(restored,'main'),null);
assert.equal(savedFit(restored,'main','sword').sizePercent,70,'reset affects only selected item');
console.log('Workshop fit persistence: passed');
