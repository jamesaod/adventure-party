import bpy,json,hashlib
from pathlib import Path
from mathutils import Vector
ROOT=Path(__file__).resolve().parents[1]
SRC=Path('C:/Users/james/Documents/Codex/asset-staging/low-poly-medieval-weapons/source/Assets/TossedSalads/LowPoly-MedievalWeapons')
OUT=ROOT/'assets/models/weapons/low-poly-medieval'; OUT.mkdir(parents=True,exist_ok=True)
bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.fbx(filepath=str(SRC/'Meshes/lowPoly_medievalWeapons.fbx'))
mat=bpy.data.materials.new('Terracotta wood and matte steel');mat.use_nodes=True
bs=mat.node_tree.nodes.get('Principled BSDF');bs.inputs['Roughness'].default_value=1
tex=mat.node_tree.nodes.new('ShaderNodeTexImage');tex.image=bpy.data.images.load(str(SRC/'Textures/tex_red.png'));tex.interpolation='Closest'
mat.node_tree.links.new(tex.outputs['Color'],bs.inputs['Base Color'])
names='arrow_1 axe_3 axe_5 bow_1 bow_1_1 bow_2 bow_2_1 bow_cross dagger_2 hammer_1 hammer_3 hammer_5 longsword_4 longsword_5 mace_1 mace_2 mace_4 quiver spear_4 spear_5 staff_1 staff_2 sword_3 sword_4 sword_5'.split()
rows={}
for name in names:
 original=bpy.data.objects[name]
 o=original.copy();o.data=original.data.copy();bpy.context.collection.objects.link(o)
 # Bake source hierarchy, center horizontally, normalize vertical length. glTF maps Z up to Y up.
 coords=[original.matrix_world@v.co for v in original.data.vertices]
 lo=Vector(tuple(min(v[i] for v in coords) for i in range(3)));hi=Vector(tuple(max(v[i] for v in coords) for i in range(3)))
 length=hi.z-lo.z
 if length<=0:raise ValueError(name)
 center=Vector(((lo.x+hi.x)/2,(lo.y+hi.y)/2,lo.z))
 o.parent=None;o.matrix_world.identity()
 for v,p in zip(o.data.vertices,coords):v.co=(p-center)/length
 o.data.materials.clear();o.data.materials.append(mat)
 bpy.ops.object.select_all(action='DESELECT');o.select_set(True);bpy.context.view_layer.objects.active=o
 o.data.calc_loop_triangles()
 extra=None
 if name in ['bow_1','bow_2']:
  o.name='BowRest'
  source=bpy.data.objects[name+'_1'];extra=source.copy();extra.data=source.data.copy();bpy.context.collection.objects.link(extra)
  points=[source.matrix_world@v.co for v in source.data.vertices]
  low=Vector(tuple(min(v[i] for v in points) for i in range(3)));high=Vector(tuple(max(v[i] for v in points) for i in range(3)))
  anchor=Vector(((low.x+high.x)/2,(low.y+high.y)/2,(low.z+high.z)/2-length/2))
  extra.parent=None;extra.matrix_world.identity();extra.name='BowDrawn'
  for v,p in zip(extra.data.vertices,points):v.co=(p-anchor)/length
  extra.data.materials.clear();extra.data.materials.append(mat);extra.select_set(True)
 path=OUT/(name+'.glb')
 bpy.ops.export_scene.gltf(filepath=str(path),export_format='GLB',use_selection=True,export_animations=False)
 rows[name]={'asset':path.relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'triangles':len(o.data.loop_triangles),'vertices':len(o.data.vertices),'sourceHeight':length}
 if extra:bpy.data.objects.remove(extra,do_unlink=True)
 bpy.data.objects.remove(o,do_unlink=True)
(ROOT/'js/low-poly-weapon-assets.mjs').write_text('// Generated by scripts/import-low-poly-weapons.py. Source geometry retained.\nexport const LOW_POLY_WEAPON_ASSETS='+json.dumps(rows,indent=2)+';\n')
print('Imported',len(rows),'selected models')
