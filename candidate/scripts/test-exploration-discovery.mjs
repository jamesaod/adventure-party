import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createExplorationState,act} from '../js/exploration-core.mjs';
import {discoveryKey,restoreDiscovery,revealDiscovery,saveDiscovery,hasSight} from '../js/exploration-discovery.mjs';
import {explorationMapMarkup} from '../js/exploration-map.mjs';
const map=JSON.parse(readFileSync(new URL('../data/exploration/old-tollhouse.json',import.meta.url)));
const state=createExplorationState(map),d=restoreDiscovery(map,null);
assert.equal(d.discovered.size,0);
assert.ok(!explorationMapMarkup(map,state,d).includes('data-cell='));
revealDiscovery(map,state,d);
assert.ok(d.discovered.has('3,9'),'First closed door is visible');
assert.ok(!d.discovered.has('3,8'),'Closed door hides corridor beyond');
assert.ok(!d.discovered.has('11,12'),'Unseen guardroom stays blank');
assert.ok(!explorationMapMarkup(map,state,d).includes('data-door="11,9"'));
for(let i=0;i<3;i++)act(map,state,'forward');
act(map,state,'door');revealDiscovery(map,state,d);
assert.ok(d.discovered.has('3,8'),'Opening door reveals corridor');
act(map,state,'door');revealDiscovery(map,state,d);
assert.ok(!d.visible.has('3,8'));assert.ok(d.discovered.has('3,8'),'Previously seen corridor persists');
const restored=restoreDiscovery(map,saveDiscovery(d));assert.deepEqual(restored.discovered,d.discovered);assert.deepEqual(restored.knownDoors,d.knownDoors);
assert.equal(restoreDiscovery(map,'invalid').discovered.size,0);
assert.equal(restoreDiscovery(map,JSON.stringify({version:1,cells:['-1,0','500,0',null,'1,1']})).discovered.size,1);
const changed=structuredClone(map);changed.grid[1]='#......#########';assert.notEqual(discoveryKey(map),discoveryKey(changed));
const corner=structuredClone(map);corner.grid[12]=corner.grid[12].substring(0,4)+'#'+corner.grid[12].substring(5);const observer={...state,x:3,z:12};
assert.equal(hasSight(corner,observer,4,11),false,'No diagonal glimpse past blocked corner');
assert.equal(hasSight(corner,observer,4,12),true,'Blocking wall itself is visible');
console.log('Discovery: unseen geometry omitted, walls/doors/corners block LOS, opened doors reveal, memory survives leaving sight and serialization, layout-isolated saves and corrupt-save recovery passed.');
