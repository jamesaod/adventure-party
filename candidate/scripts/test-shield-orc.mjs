import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {ITEM_CATALOG} from '../js/item-catalog.mjs';
import {studioShield,normalizeShield} from '../js/studio-shield.mjs';
import {VISIBLE_SHIELD_ASSETS} from '../js/mob-appearance.mjs';
import {resolveEquipmentLibrary} from '../js/equipment-library-core.mjs';
import {offHandItems} from '../js/mob-generation.mjs';
const item=ITEM_CATALOG['shield-orc'],preset=studioShield(item.id);
assert.equal(item.name,'Shield, Orc');assert.equal(preset.label,item.name);
assert.equal(normalizeShield({leftHandShield:item.id}).leftHandShield,item.id);
assert.equal(VISIBLE_SHIELD_ASSETS[item.id].asset,item.appearance.asset);
assert.equal(resolveEquipmentLibrary()[item.id].name,item.name);
assert.ok(offHandItems().some(i=>i.id===item.id));
const b=readFileSync(new URL('../'+item.appearance.asset,import.meta.url));
assert.equal(b.length,item.appearance.runtimeAsset.bytes);assert.equal(createHash('sha256').update(b).digest('hex'),item.appearance.runtimeAsset.sha256);
const len=b.readUInt32LE(12),g=JSON.parse(b.subarray(20,20+len).toString()),bin=28+len;
assert.equal(g.meshes.flatMap(m=>m.primitives).reduce((n,p)=>n+g.accessors[p.indices].count/3,0),622);
assert.equal(g.images.length,1);const v=g.bufferViews[g.images[0].bufferView],png=b.subarray(bin+(v.byteOffset||0),bin+(v.byteOffset||0)+v.byteLength);
assert.equal(png.readUInt32BE(16),256);assert.equal(png.readUInt32BE(20),256);
assert.equal(studioShield('round-wooden-shield').presetRevision,4);
console.log('Shield, Orc: catalog, Studio, MOB eligibility, combat appearance, asset hash, 622 triangles and 256px texture passed.');
