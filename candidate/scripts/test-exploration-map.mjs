import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createExplorationState,act} from '../js/exploration-core.mjs';
import {explorationMapMarkup} from '../js/exploration-map.mjs';
const map=JSON.parse(readFileSync(new URL('../data/exploration/old-tollhouse.json',import.meta.url)));
const state=createExplorationState(map);
const discovery={discovered:new Set(map.grid.flatMap((r,z)=>[...r].map((_,x)=>`${x},${z}`))),knownDoors:new Map()};
let drawing=explorationMapMarkup(map,state,discovery);
assert.equal((drawing.match(/data-cell=/g)||[]).length,256);
assert.equal((drawing.match(/data-kind="wall"/g)||[]).length,126);
assert.equal((drawing.match(/data-door=/g)||[]).length,4);
assert.ok(drawing.includes('data-party="3,13,0"'));
for(let i=0;i<3;i++)act(map,state,'forward');
act(map,state,'door');discovery.knownDoors.set('3,9',true);drawing=explorationMapMarkup(map,state,discovery);
assert.ok(drawing.includes('data-door="3,9" data-open="true"'));
act(map,state,'forward');act(map,state,'right');drawing=explorationMapMarkup(map,state,discovery);
assert.ok(drawing.includes('data-party="3,9,1"'));
assert.ok(drawing.includes('column 4, row 10, facing East'));
discovery.knownDoors.clear();const reset=explorationMapMarkup(map,createExplorationState(map),discovery);
assert.ok(!reset.includes('data-open="true"'));
assert.ok(reset.includes('data-party="3,13,0"'));
console.log('Parchment map matches the 256-cell grid and follows live doors, movement, facing and restart.');
